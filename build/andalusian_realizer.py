def _letters(s):
    """Arabic letter stream only: used to re-check a quotation against the corpus."""
    keep = set('\u0623\u0625\u0622\u0629\u0649\u0624\u0626')
    return ''.join(c for c in strip_diac(s)
                   if '\u0621' <= c <= '\u064A' or c in keep)


def _corpus_path(rel):
    base = os.path.basename(rel)
    for d in CORPUS_DIRS:
        for cand in (os.path.join(d, rel), os.path.join(d, base)):
            if os.path.exists(cand):
                return cand
    return None


def verify_citations(verbose=True):
    """Re-check EVERY quotation in CITATIONS against the corpus file it names."""
    ok, bad, missing = 0, [], 0
    for key, c in CITATIONS.items():
        p = _corpus_path(c['file'])
        if p is None:
            missing += 1
            continue
        with open(p, encoding='utf-8') as fh:
            hay = _letters(fh.read())
        needle = _letters(c['arabic'])
        if needle and needle in hay:
            ok += 1
        else:
            bad.append(key)
    if verbose:
        present = len(CITATIONS) - missing
        print(f'  citations re-checked against the corpus: {ok}/{present} verbatim'
              + (f'  ({missing} corpus file(s) not present here)' if missing else ''))
        for k in bad:
            print(f'    [FAIL] {k} NOT found verbatim in {CITATIONS[k]["file"]}')
    return not bad


