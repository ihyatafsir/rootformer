class AndalusianRealizer:
    """One coherent API over the three implemented grammar algorithms."""

    # the wrapper keeps the verified primitives; it does not copy them
    _irab = IrabRealizer()
    _iktifa = IktifaSaturation()
    _apocope = JussiveApocope()

    def __init__(self, vocab=None):
        self.vocab = vocab

    # =============================================================================
    # 1. THE DIPTOTE (mamnu' min al-sarf)
    # =============================================================================
    @staticmethod
    def _is_additional_alif(bare: str, root: str = '') -> bool:
        """True when a final alif/alif-maqsura/hamza is ZA'IDAH, not the third radical.

        Sources: `usfur_diptote_two_causes` (al-ta'nith al-lazim = the hamza as in حمراء
        or the alif as in حبلى) and `usfur_mamdud_hamza_is_alif` (that hamza is a badal
        from alif al-ta'nith).  A final weak or hamza RADICAL makes the noun MUNSARIF:
        فتى (root فتي), عصا (root عصو), قرّاء (root قرأ).
        """
        if not root:
            return True                       # no root supplied: the surface default
        r = strip_diac(root)
        if not r:
            return True
        return r[-1] not in _WEAK_OR_HAMZA

    @staticmethod
    def feminine_alif(bare: str, wazn: str = '', root: str = '') -> bool:
        """al-ta'nith al-lazim -- a SINGLE cause that stands in place of two."""
        b = strip_diac(bare)
        if not b:
            return False
        if b.endswith('اء'):                  # mamdud: hamza < alif al-ta'nith
            return AndalusianRealizer._is_additional_alif(b, root)
        if b.endswith(('ى', 'ا')):            # maqsura / plain alif
            if not AndalusianRealizer._is_additional_alif(b, root):
                return False
            w = strip_diac(wazn)
            if w:
                return w.startswith(_FEM_ALIF_WAZAN) or len(w) > 3
            return True
        return False

    @staticmethod
    def sighat_muntaha(wazn: str) -> bool:
        """The ultimate plural (مفاعل / مفاعيل) -- the SECOND single cause."""
        w = strip_diac(wazn or '')
        return w.startswith(_SIGHAT_MUNTAHA)

    @classmethod
    def is_diptote(cls, word_bare, wazn_name='', is_proper=False, is_feminine=False,
                   root='', is_foreign=False, is_compound=False,
                   is_adjective=False) -> bool:
        """Ibn 'Usfur's rule: TWO causes, or ONE that stands in place of two.

        «والاسم الذي لا ينصرف هو كل اسم اجتمعت فيه علتان فرعيتان فصاعدا عن علل تسع ...
        أو وجد فيه علة تقوم مقام علتين ... والعلة التي تقوم من هذه العلل مقام علتين:
        التأنيث اللازم والجمع الذي لا نظير له في الآحاد.»
        """
        # --- a single cause suffices ---
        if cls.sighat_muntaha(wazn_name):
            return True
        if cls.feminine_alif(word_bare, wazn_name, root):
            return True
        # --- otherwise two causes must combine (ENGINEERING counting, see RULE_SOURCES) ---
        causes = 0
        if is_proper:
            causes += 1                       # التعريف (العلمية)
        if is_feminine:
            causes += 1                       # التأنيث
        if is_adjective:
            causes += 1                       # الصفة
        if is_foreign:
            causes += 1                       # العجمة
        if is_compound:
            causes += 1                       # التركيب
        w = strip_diac(wazn_name or '')
        if w.startswith(_ALIF_NUN_WAZAN):
            causes += 1                       # زيادة الألف والنون
        if w.startswith(_WAZN_FIL_WAZAN):
            causes += 1                       # وزن الفعل
        return causes >= 2

    # =============================================================================
    # 2. I'RAB REALISATION
    # =============================================================================
    @staticmethod
    def _case(case):
        if case is None:
            return None
        s = strip_diac(str(case)).strip()
        return CASE_ALIASES.get(s.lower(), CASE_ALIASES.get(s))

    def realize(self, word, case, wazn='', root='', **flags) -> str:
        """Realise the i'rab ending of `word` for `case` (raf / nasb / jarr / jazm).

        Recognised flags: is_proper, is_feminine, is_adjective, is_foreign, is_compound,
        is_dual, is_plural_m, is_plural_f, is_mudaf, has_al; `wazn_name` is accepted as
        an alias of `wazn`.
        """
        c = self._case(case)
        if c is None:
            return word
        if not wazn and flags.get('wazn_name'):
            wazn = flags.pop('wazn_name')
        b = strip_diac(word)
        if not b:
            return word

        is_dual = bool(flags.get('is_dual'))
        is_pm = bool(flags.get('is_plural_m'))
        is_pf = bool(flags.get('is_plural_f'))
        # the five nouns, the dual and the two sound plurals take LETTER endings
        # (Ibn Malik's niyaba); the verified realiser owns those, so delegate unchanged.
        letter_ending = (is_dual or is_pm or is_pf or b in _ASMA_KHAMSA
                         or b.rstrip('وةاي') in {'أب', 'أخ', 'حم', 'فو', 'ذو'})

        if c == 'jarr' and not letter_ending:
            diptote = (not flags.get('is_mudaf') and not flags.get('has_al')
                       and self.is_diptote(b, wazn, root=root,
                                           is_proper=flags.get('is_proper', False),
                                           is_feminine=flags.get('is_feminine', False),
                                           is_adjective=flags.get('is_adjective', False),
                                           is_foreign=flags.get('is_foreign', False),
                                           is_compound=flags.get('is_compound', False)))
            if diptote:
                # the fathah is ESTIMATED (muqaddarah) on a final alif or on a final
                # weak radical (al-manqus); it SHOWS on the mamdud's hamza.
                if (b.endswith(('ى', 'ا')) and not b.endswith('اء')) or \
                        (root and b[-1] in _WEAK_OR_HAMZA and strip_diac(root)[-1] in 'اويى'):
                    return b
                return b + FATHA
            # munsarif, or a diptote released by idafa / al-: always kasrah in jarr
            return b + KASRA

        kwargs = {k: v for k, v in flags.items()
                  if k in ('is_proper', 'is_feminine', 'is_dual', 'is_plural_m', 'is_plural_f')}
        return self._irab.realize(word, c, wazn_name=wazn, root=root, **kwargs)

    # =============================================================================
    # 3. AL-IKTIFA' -- clitic saturation
    # =============================================================================
    HOST_ALIASES = {'verb': 'verb', 'fi_l': 'verb', 'fil': 'verb', 'فعل': 'verb',
                    'noun': 'noun', 'ism': 'noun', 'اسم': 'noun',
                    'prep': 'prep', 'harf': 'prep', 'حرف': 'prep', 'preposition': 'prep'}

    @classmethod
    def slot_of(cls, clitic, host_class):
        """Which valency slot the clitic saturates, or None.  The slot depends on the
        HOST -- Sibawayh: the pronoun sign «لا يتكلم به مفردا حتى يكون متصلا بفعل قبله
        أو باسم فيه ضمير»;  verb -> maf'ul bihi / fa'il, noun -> mudaf ilayhi,
        preposition -> majrur."""
        host = cls.HOST_ALIASES.get(str(host_class).strip().lower())
        if host is None:
            raise ValueError(f'unknown host class {host_class!r}; expected one of '
                             f'{sorted(set(cls.HOST_ALIASES))}')
        return cls._iktifa.saturates(clitic, host)

    @classmethod
    def saturates(cls, clitic, host_class) -> bool:
        """True when the clitic closes the host's valency slot (al-iktifa')."""
        return cls.slot_of(clitic, host_class) is not None

    @classmethod
    def closes_slot(cls, host_class, suffix, verb_is_lazim=False, noun_suffices=False):
        """The full three-way closure: filled | licitly absent | saturated by a clitic."""
        host = cls.HOST_ALIASES.get(str(host_class).strip().lower(), host_class)
        return cls._iktifa.closes_slot(host, suffix, verb_is_lazim, noun_suffices)

    # =============================================================================
    # 4. JUSSIVE APOCOPE
    # =============================================================================
    @classmethod
    def jussive(cls, verb, root='', has_clitic=False, has_energetic=False) -> str:
        """Realise the jussive: sound -> sukun, naqis -> delete the final weak letter,
        ajwaf -> medial elision; a clitic or the energetic nun protects the ending.

        Ibn 'Usfur: «وللجزم علامتان: السكون والحذف ... فالحذف يكون علامة للجزم فيما آخره
        حرف علة ... والسكون: علامة للجزم فيما رفع بالضمة الظاهرة».  Sibawayh: «الآخر
        إذا كان يسكن في الرفع حذف في الجزم ... لم يرم ولم يغز ولم يخش»;  «لم يبع ولم
        يقل» (ajwaf);  «ارمه، ولم يغزه، واخشه، ولم يقضه، ولم يرضه» (the attached ha'
        protects the ending);  «فعل الواحد إذا كان مجزوما فلحقته الخفيفة والثقيلة حركت
        المجزوم» (the energetic nun).
        """
        return cls._apocope.jussive(verb, root=root, has_clitic=has_clitic,
                                    has_energetic=has_energetic)

    @classmethod
    def imperative(cls, imperfect, root='', wazn='') -> str:
        """The amr built on the jussive stem (Ibn Malik, Lamiyyat al-Af'al:
        «كالمضارع ذي الجزم ... وبهمز الوصل منكسرا صل ساكنا كان بالمحذوف متصلا»)."""
        return cls._apocope.imperative(imperfect, root=root, wazn_name=wazn)

    # =============================================================================
    # 5. AL-SHATIBI'S WAW
    # =============================================================================
    NOMINAL = {'ism', 'اسم', 'sifah', 'صفة', 'noun', 'n', 'adj', 'na_t', "na't"}
    VERBAL = {'fil', 'فعل', 'verb', 'v', 'fi_l'}
    PARTICLE = {'harf', 'حرف', 'particle', 'p'}

    @classmethod
    def _pos(cls, label):
        """Normalise an English or Arabic POS label to ISM / FIL / HARF / START."""
        if label is None:
            return None
        s = str(label).strip()
        low = s.lower()
        if low in ('start', 'begin', 'bos') or s == 'START':
            return 'START'
        if low in cls.NOMINAL:
            return 'ISM'
        if low in cls.VERBAL:
            return 'FIL'
        if low in cls.PARTICLE:
            return 'HARF'
        return 'ISM' if not s else low.upper()

    @classmethod
    def maa_substitution_test(cls, maa_fits=None) -> bool:
        """Ibn Malik's operational test: does «مع» fit in the waw's place?

        VERBATIM (Ibn Malik, al-Tashil al-Fawa'id):
          «ويميز "واو" الجمع تقدير "مع" موضعها»  (the waw of jam' is distinguished by
                                                  estimating «مع» in its place)
          «... جاز النصب على المعية وعلى إضمار الفعل اللائق إن حسن "مع" موضع الواو
            وإلا تعين الإضمار»  (if «مع» fits in the waw's place, naṣb on ma'iyya is
                                 allowed; otherwise the implied (verb) is fixed)
        and independently (al-Shatibi, al-Maqasid al-Shafiyya): the waw must be
        «معينة لمعنى مع»; where «مع» cannot be estimated the waw is «عاطفة لمجرد الجمع».

        The judgment itself is semantic -- it is the caller's (or the LM's) -- so this
        helper only makes the test explicit and returns it; `maa_fits=False` does NOT
        return MAIYYA, it forces the 'atf / isti'naf reading.
        """
        return bool(maa_fits)

    @classmethod
    def waw_function(cls, prev_cls, next_cls, start_of_clause=False, oath=False,
                     maahu_context=False, maa_fits=None) -> str:
        """Classify the waw: ATF | HAL | ISTINAF | QASAM (+ MAIYYA by Ibn Malik's test).

        The four required functions, verbatim in CITATIONS:
          ATF      «لأن واو العطف شركت بينهما في العامل»
          HAL      «فقوله: {ولها كتاب معلوم} جملة حالية مصدرة بواو الحال»
          ISTINAF  «لأنه إما للتشريك، ولا إشكال، وإما للاستئناف»
          QASAM    «الواو القسمية والعاطفة»; the negative test is Ibn Sayyidih's
                   «والواو فيها واو العطف لا واو القسم»
        MAIYYA   Ibn Malik's «مع» substitution test -- see maa_substitution_test().
                   `maa_fits=True` (or the explicit `maahu_context=True`) returns MAIYYA;
                   `maa_fits=False` forces the 'atf / isti'naf reading.
        The ORDER and the POS matrix are ENGINEERING (see RULE_SOURCES['waw.pos_matrix']).
        """
        prev, nxt = cls._pos(prev_cls), cls._pos(next_cls)
        if oath:                                   # matches ShatibiWawV2.classify order
            return 'QASAM'
        if start_of_clause or prev == 'START':
            return 'ISTINAF'
        if maahu_context or cls.maa_substitution_test(maa_fits):
            return 'MAIYYA'                        # Ibn Malik: «مع» fits in the waw's place
        if prev in ('ISM', 'SIFAH') and nxt == 'FIL':
            return 'HAL'
        if prev in ('ISM', 'SIFAH') and nxt in ('ISM', 'SIFAH'):
            return 'ATF'
        if prev == 'FIL' and nxt == 'FIL':
            return 'ATF'
        return 'ISTINAF'

    @classmethod
    def implied_an(cls, prev_cls, next_cls, affirmative=True, istinaf=False) -> bool:
        """Is the naṣb-giving «أن» implied after this waw?

        VERBATIM (Ibn Malik, al-Tashil al-Fawa'id): «وتضمر "أن" الناصبة أيضا لزوما بعد
        "واو" الجمع الواقعة في مواضع "الفاء"، فإن عطف بهما أو ب"أو" على فعل قبل، أو قصد
        الاستئناف بطل إضمار "ان"».
        So the implication holds in a non-affirmative context after the waw of jam', and is
        CANCELLED when the waw coordinates onto a preceding VERB or when isti'naf is
        intended.  The rule is Basran in origin and stated for the waw by al-Mubarrad,
        al-Muqtadab: «فمعنى الواو الجمع بين الشيئين. ونصبها على إضمار أن؛ كما كان في
        الفاء», and by Ibn al-Sarraj -- «الواو تنصب ما بعدها في غير الواجب من حيث انتصب
        ما بعد الفاء» -- as quoted in Ibn Malik, Sharh al-Kafiyah.
        """
        if affirmative:                            # «في غير الواجب» -- non-affirmative only
            return False
        if istinaf:                                # «أو قصد الاستئناف بطل إضمار أن»
            return False
        if cls._pos(prev_cls) == 'FIL':             # «فإن عطف ... على فعل قبل»
            return False
        return cls._pos(next_cls) == 'FIL'

    # =============================================================================
    # 6. THE DECODER HOOK
    # =============================================================================
    @classmethod
    def host_class_of(cls, root='', wazn='', override=None) -> str:
        if override:
            return cls.HOST_ALIASES.get(str(override).strip().lower(), override)
        if str(root).startswith('<P:'):
            return 'prep'                       # a particle root is not a stem
        w = wazn or ''
        if w:
            if w[-1] in _HARAKAT:               # the pattern itself ends in a short vowel
                return 'verb'
            if strip_diac(w).startswith(_VERB_WAZN_VIA_WASL):
                return 'verb'
        return 'noun'

    def analyze_tuple(self, vocab, p_id, r_id, w_id, s_id, case=None, **flags):
        """Everything the decode path needs for one (prefix, root, wazn, suffix) event.

        Returns surface word, i'rab-realised word, the slot the suffix saturates and
        whether that closed the host's slot, plus the jussive form for a verb under
        jazm.  Never raises on a missing wazn/suffix -- the model's inventory is partial
        by construction.
        """
        root = vocab.id2root.get(r_id, '')
        wazn = vocab.id2wazn.get(w_id, '')
        suffix = vocab.id2suffix.get(s_id, '')
        surface = vocab.decode_word(p_id, r_id, w_id, s_id)
        s_bare = strip_diac(suffix or '')
        if s_bare in ('<NONE>', '<PAD>', '<UNK>'):
            s_bare = ''
        host = self.host_class_of(root, wazn, override=flags.get('host_class'))
        c = self._case(case if case is not None else flags.get('case'))

        realised = None
        if host == 'verb' and c == 'jazm':
            realised = self.jussive(surface, root=root,
                                    has_clitic=bool(s_bare) and self.saturates(s_bare, 'verb'))
        elif c:
            realised = self.realize(surface, c, wazn=wazn, root=root, **flags)

        closed, why = self.closes_slot(host, s_bare) if s_bare else (False, 'no clitic')
        return {
            'surface': surface,
            'host_class': host,
            'case': c,
            'irab': realised,
            'saturated_slot': self.slot_of(s_bare, host) if s_bare else None,
            'slot_closed': closed,
            'slot_reason': why,
            'wazn': wazn,
            'root': root,
        }

    def install(self, vocab):
        """Attach this realizer to a vocab so the decode path can find it as
        `vocab.andalusian_realizer` -- additive; changes no existing behaviour."""
        self.vocab = vocab
        vocab.andalusian_realizer = self
        return self


