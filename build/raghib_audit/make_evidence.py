#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Generate the side-by-side evidence appendix (markdown).

Every Arabic passage shown here was retrieved from the named file at the given
line, and every record quote was mechanically re-checked as an exact substring
of that source (see verify_verdicts.py: 780/780 checks passed).
"""
import json
import textwrap

ENR = "/home/grem3/Documents/deepseek-harness/default-workspace/rootformer/build/raghib_audit/fidelity_sample_enriched.json"
VER = "/home/grem3/Documents/deepseek-harness/default-workspace/rootformer/build/raghib_audit/verdicts_final.json"
OUT = "/home/grem3/Documents/deepseek-harness/default-workspace/rootformer/build/raghib_audit/EVIDENCE_APPENDIX.md"


def wrap(s, n=100):
    return "\n".join(textwrap.wrap((s or "").replace("\n", " "), n)) or "(none)"


def src_block(e, k):
    src = e["sources"].get(k)
    if not src:
        return "_no entry in this source_"
    if k == "asas":
        parts = []
        for x in src["entries"][:3]:
            parts.append("  [%s] %s" % (x["mode"], x["text"][:520]))
        return "\n".join(parts)
    return "  line %s, header `%s`:\n  %s" % (src["line"], src["header"], src["text"][:620])


def main():
    S = {e["root"]: e for e in json.load(open(ENR, encoding="utf-8"))["bundle"]}
    V = json.load(open(VER, encoding="utf-8"))
    verd = {c["root"]: c for c in V}

    wrong_roots = sorted({c["root"] for c in V for k in ("mufradat", "maqayis", "asas")
                          if c[k + "_verdict"] == "WRONG"})
    # pick representative agreements / partials with a verified quote
    agree, partial = [], []
    for c in V:
        for k in ("mufradat", "maqayis", "asas"):
            v = c[k + "_verdict"]
            if v == "AGREES" and c[k + "_quote"] and len(agree) < 8:
                agree.append((c["root"], k))
                break
        for k in ("mufradat", "maqayis", "asas"):
            if c[k + "_verdict"] == "PARTIAL" and c[k + "_quote"] and len(partial) < 6:
                partial.append((c["root"], k))
                break

    L = []
    L.append("# Side-by-side evidence appendix\n")
    L.append("Generated by `make_evidence.py`. Every Arabic passage below is text retrieved from the "
             "named file at the stated line; every quotation returned by the adjudication pass was "
             "mechanically re-checked as an exact substring of that source (780/780 checks passed, "
             "0 fabricated).\n")

    L.append("\n## A. All WRONG verdicts (14 distinct roots, 15 verdicts)\n")
    L.append("A WRONG verdict means the record contradicts the named source, or the gloss plainly "
             "belongs to a different root.\n")
    for r in wrong_roots:
        c, e = verd[r], S[r]
        L.append("\n### `%s`\n" % r)
        for k in ("mufradat", "maqayis", "asas"):
            if c[k + "_verdict"] != "WRONG":
                continue
            L.append("**Check vs %s — WRONG**\n" % k)
            L.append("- RECORD `ontological_core`: %s\n" % wrap(e["record"].get("ontological_core"), 110))
            L.append("- RECORD `haqiqah_literal`: %s\n" % wrap(e["record"].get("haqiqah_literal"), 110))
            L.append("- SOURCE (%s):\n\n```\n%s\n```\n" % (k, src_block(e, k)))
            L.append("- Adjudicator's ground (the quoted passage): %s\n" % wrap(c[k + "_reason"], 110))
            L.append("- Verified quote: `%s`\n" % c[k + "_quote"][:160])

    L.append("\n## B. Representative PARTIAL verdicts\n")
    for r, k in partial:
        c, e = verd[r], S[r]
        L.append("\n### `%s` — %s (PARTIAL)\n" % (r, k))
        L.append("- RECORD `ontological_core`: %s\n" % wrap(e["record"].get("ontological_core"), 110))
        L.append("- RECORD `haqiqah_literal`: %s\n" % wrap(e["record"].get("haqiqah_literal"), 110))
        L.append("- SOURCE (%s):\n\n```\n%s\n```\n" % (k, src_block(e, k)))
        L.append("- Why PARTIAL: %s\n" % wrap(c[k + "_reason"], 110))
        L.append("- Verified quote: `%s`\n" % c[k + "_quote"][:160])

    L.append("\n## C. Representative AGREES verdicts\n")
    for r, k in agree:
        c, e = verd[r], S[r]
        L.append("\n### `%s` — %s (AGREES)\n" % (r, k))
        L.append("- RECORD `canonical_definition.ar`: %s\n" %
                 wrap((e["record"].get("canonical_definition") or {}).get("arabic"), 110))
        L.append("- SOURCE (%s):\n\n```\n%s\n```\n" % (k, src_block(e, k)))
        L.append("- Why AGREES: %s\n" % wrap(c[k + "_reason"], 110))
        L.append("- Verified quote: `%s`\n" % c[k + "_quote"][:160])

    open(OUT, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", OUT, "cases:", len(wrong_roots), "+", len(partial), "+", len(agree))


if __name__ == "__main__":
    main()
